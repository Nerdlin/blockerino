// Turns the Stockfish.js engine from node_modules (npm "stockfish" 10.0.2, the pure JavaScript build, GPLv3) into a
// module that holds its source as a string. The game starts it as a separate program: a Web Worker on the web and
// in an invisible WebView on phones, and talks to it over UCI messages only. Run after changing the package version:
//   node scripts/build-stockfish-module.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const pkg = JSON.parse(fs.readFileSync(path.join(root, "node_modules/stockfish/package.json"), "utf8"));
const source = fs.readFileSync(path.join(root, "node_modules/stockfish/src/stockfish.asm.js"), "utf8");
const out = path.join(root, "constants/chess/engine/stockfishSource.ts");
fs.writeFileSync(
	out,
	`// Generated by scripts/build-stockfish-module.mjs from npm "stockfish" ${pkg.version} (src/stockfish.asm.js).\n` +
		"// Stockfish.js: https://github.com/nmrugg/stockfish.js, Stockfish: https://stockfishchess.org, licensed GPLv3\n" +
		"// (license text in assets/licenses/stockfish-COPYING.txt). It runs as a separate program and is driven over UCI.\n" +
		"/* eslint-disable */\n" +
		`export const STOCKFISH_VERSION = ${JSON.stringify(pkg.version)};\n` +
		`export const STOCKFISH_SOURCE: string = ${JSON.stringify(source)};\n`,
);
fs.mkdirSync(path.join(root, "assets/licenses"), { recursive: true });
fs.copyFileSync(path.join(root, "node_modules/stockfish/Copying.txt"), path.join(root, "assets/licenses/stockfish-COPYING.txt"));
console.log(`wrote ${path.relative(root, out)} (${(source.length / 1024).toFixed(0)} KB of engine source)`);
