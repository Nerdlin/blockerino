// Renders every skin texture (constants/SkinTextures.ts) to a PNG, so a phone shows the skin's surface with one shared
// image per skin instead of one SVG per block (react-native-svg draws each SVG into its own bitmap on Android, which
// made opening a game and dragging a piece slow). Run after changing a sprite: npx sucrase-node scripts/build-skin-textures.ts
import { deflateSync } from "zlib";
import { mkdirSync, writeFileSync } from "fs";
import { join } from "path";
import { SKIN_SPRITES, TEX, paint } from "../constants/SkinTextures";

const SCALE = 8; // 16x16 texture pixels -> 128x128 PNG, sharp enough after the phone scales it to a block
const OUT = join(__dirname, "..", "assets", "images", "skin-textures");

const CRC = new Int32Array(256).map((_, n) => {
	let c = n;
	for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
	return c;
});
function crc32(buf: Buffer): number {
	let c = -1;
	for (const b of buf) c = CRC[(c ^ b) & 255] ^ (c >>> 8);
	return (c ^ -1) >>> 0;
}
function chunk(type: string, data: Buffer): Buffer {
	const len = Buffer.alloc(4);
	len.writeUInt32BE(data.length);
	const td = Buffer.concat([Buffer.from(type, "ascii"), data]);
	const crc = Buffer.alloc(4);
	crc.writeUInt32BE(crc32(td));
	return Buffer.concat([len, td, crc]);
}
function rgba(col: string): [number, number, number, number] {
	const m = /rgba\((\d+),(\d+),(\d+),([\d.]+)\)/.exec(col);
	if (!m) throw new Error(`unexpected colour ${col}`);
	return [Number(m[1]), Number(m[2]), Number(m[3]), Math.round(Number(m[4]) * 255)];
}
function png(px: (string | null)[]): Buffer {
	const size = TEX * SCALE;
	const raw = Buffer.alloc(size * (size * 4 + 1));
	for (let y = 0; y < size; y++) {
		const row = y * (size * 4 + 1);
		raw[row] = 0;
		for (let x = 0; x < size; x++) {
			const col = px[Math.floor(y / SCALE) * TEX + Math.floor(x / SCALE)];
			if (col) raw.set(rgba(col), row + 1 + x * 4);
		}
	}
	const ihdr = Buffer.alloc(13);
	ihdr.writeUInt32BE(size, 0);
	ihdr.writeUInt32BE(size, 4);
	ihdr[8] = 8;
	ihdr[9] = 6;
	return Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), chunk("IHDR", ihdr), chunk("IDAT", deflateSync(raw, { level: 9 })), chunk("IEND", Buffer.alloc(0))]);
}

mkdirSync(OUT, { recursive: true });
const ids = Object.keys(SKIN_SPRITES).sort();
for (const id of ids) writeFileSync(join(OUT, `${id}.png`), png(paint(id)!));
const lines = ids.map((id) => `\t${id}: require("../assets/images/skin-textures/${id}.png"),`);
writeFileSync(
	join(__dirname, "..", "constants", "SkinTextureImages.ts"),
	`// Generated by scripts/build-skin-textures.ts from constants/SkinTextures.ts. Do not edit by hand.\n/* eslint-disable @typescript-eslint/no-require-imports */\nexport const SKIN_TEXTURE_IMAGES: Record<string, number> = {\n${lines.join("\n")}\n};\n`,
);
console.log(`${ids.length} textures`);
