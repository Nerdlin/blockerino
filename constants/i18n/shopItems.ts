export function shopItemText(item: Pick<ShopItem, "id" | "title" | "description">, language: Language): { title: string; description: string } {
	const ru = language === "ru" ? RU[item.id] : undefined;
	return ru ? { title: ru[0], description: ru[1] } : { title: item.title, description: item.description };
}

